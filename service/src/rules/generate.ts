import { hashContent, ruleEndMarker, ruleStartMarker } from '@neon/core'
import { and, eq, inArray } from 'drizzle-orm'
import type { Db } from '../db/client.js'
import { components, decisions, generatedRules } from '../db/schema.js'

/**
 * Path-scoped rules, generated from decisions.
 *
 * A constraint attached to the files it governs loads itself when an agent
 * touches them, and stays out of context entirely otherwise: no MCP call, no
 * token budget, no retrieval failure mode. It is the cheapest and most reliable
 * way to get a constraint in front of an agent, so anything expressible this
 * way belongs here rather than in the context pack — and assembly deliberately
 * leaves those decisions out.
 *
 * Two rules govern this whole subsystem:
 *
 *   - the repo holds the text, Neon holds the hash. If Neon held the rule text
 *     it would be the only copy of something, which is a bug by definition.
 *   - a human confirms every write. Nothing here commits anything.
 */

export type RuleAction = 'create' | 'update' | 'remove' | 'unchanged'

export interface RulePlanItem {
  decisionId: string
  decisionKey: string
  decisionTitle: string
  componentId: string | null
  componentName: string | null
  /** Where the rule belongs, relative to the repo root. */
  path: string
  globs: string[]
  /** The managed block, markers included. Empty for a removal. */
  block: string
  contentHash: string
  action: RuleAction
  /** Why this rule exists or is going, in one line. */
  reason: string
}

const START = ruleStartMarker
const END = ruleEndMarker

/**
 * The directories a component's globs are rooted in — one per glob, not their
 * common ancestor.
 *
 * A component spanning `src/retrieval/**` and `src/rank/**` gets a rule in each
 * of them rather than one in `src/`. Hoisting to the common ancestor would put
 * the constraint in front of everyone working anywhere under it, which is the
 * failure mode path-scoping exists to avoid. An empty string means the repo
 * root, which is the honest answer for a glob with no stable prefix.
 */
export function directoriesFor(globs: string[]): string[] {
  const directories = [
    ...new Set(
      globs.map((glob) => {
        const parts = glob.split('/')
        const wildcard = parts.findIndex((part) => part.includes('*'))
        return (wildcard === -1 ? parts.slice(0, -1) : parts.slice(0, wildcard)).join('/')
      }),
    ),
  ]

  // A rule in `src/api` already covers `src/api/routes`, so keep the ancestor
  // and drop what it contains: fewer files, same reach.
  return directories.filter(
    (directory) =>
      !directories.some((other) => other !== directory && directory.startsWith(`${other}/`)),
  )
}

export function renderRule(decision: {
  key: string
  title: string
  rationale: string
  rejectedAlternatives: { title: string; why: string }[]
  state: string
}, globs: string[]): string {
  const lines = [
    START(decision.key),
    `<!-- generated by Neon from decision ${decision.key}. Edit the decision, not this block. -->`,
    '',
    `## ${decision.title}`,
    '',
    `Applies to: ${globs.join(', ')}`,
    '',
    decision.rationale.trim(),
  ]

  if (decision.rejectedAlternatives.length > 0) {
    lines.push('', 'Already considered and rejected:')
    for (const alternative of decision.rejectedAlternatives) {
      lines.push(`- **${alternative.title}** — ${alternative.why}`)
    }
  }

  if (decision.state === 'contested') {
    lines.push('', 'This decision is contested: treat it as the current shape, not as settled.')
  }

  lines.push('', END(decision.key))
  return lines.join('\n')
}

/**
 * What should change in this repo's rule files. Nothing is written here — the
 * plan is the product, and a person decides whether it happens.
 */
export async function planRules(db: Db, repoId: string): Promise<RulePlanItem[]> {
  const repoComponents = await db.select().from(components).where(eq(components.repoId, repoId))
  if (repoComponents.length === 0) return []

  const existing = await db
    .select()
    .from(generatedRules)
    .where(and(eq(generatedRules.repoId, repoId), inArray(generatedRules.state, ['proposed', 'applied'])))

  const relevant = await db
    .select()
    .from(decisions)
    .where(inArray(decisions.state, ['accepted', 'contested', 'superseded']))

  const plan: RulePlanItem[] = []
  const seen = new Set<string>()

  for (const decision of relevant) {
    for (const component of repoComponents) {
      if (!decision.componentIds.includes(component.id)) continue

      const globs = component.pathGlobs

      for (const directory of directoriesFor(globs)) {
        const scopedGlobs = globs.filter((glob) => glob.startsWith(directory))
        const path = directory ? `${directory}/CLAUDE.md` : 'CLAUDE.md'
        const key = `${decision.id}:${path}`
        const current = existing.find((r) => r.decisionId === decision.id && r.path === path)

        // A superseded decision's constraint has to leave, or the repo keeps
        // telling agents something the team no longer believes.
        if (decision.state === 'superseded') {
          if (current) {
            seen.add(key)
            plan.push({
              decisionId: decision.id,
              decisionKey: decision.key,
              decisionTitle: decision.title,
              componentId: component.id,
              componentName: component.name,
              path,
              globs: scopedGlobs,
              block: '',
              contentHash: '',
              action: 'remove',
              reason: `${decision.key} was superseded; its rule still tells agents to follow it`,
            })
          }
          continue
        }

        const block = renderRule(decision, scopedGlobs)
        const contentHash = hashContent(block)
        seen.add(key)

        plan.push({
          decisionId: decision.id,
          decisionKey: decision.key,
          decisionTitle: decision.title,
          componentId: component.id,
          componentName: component.name,
          path,
          globs: scopedGlobs,
          block,
          contentHash,
          action: !current ? 'create' : current.contentHash === contentHash ? 'unchanged' : 'update',
          reason: `${decision.key} constrains ${component.name}`,
        })
      }
    }
  }

  // Rules whose decision no longer touches any component here: also removals.
  for (const rule of existing) {
    if (seen.has(`${rule.decisionId}:${rule.path}`)) continue
    const decision = relevant.find((d) => d.id === rule.decisionId)
    plan.push({
      decisionId: rule.decisionId,
      decisionKey: decision?.key ?? rule.decisionId,
      decisionTitle: decision?.title ?? '(decision no longer present)',
      componentId: rule.componentId,
      componentName: null,
      path: rule.path,
      globs: rule.pathGlobs,
      block: '',
      contentHash: '',
      action: 'remove',
      reason: 'the decision behind this rule no longer constrains a component in this repo',
    })
  }

  return plan
}

/** Record what a human actually applied, so drift can be detected later. */
export async function recordApplied(
  db: Db,
  repoId: string,
  applied: {
    decisionId: string
    componentId: string | null
    path: string
    globs: string[]
    contentHash: string
    state: 'proposed' | 'applied' | 'removed'
  }[],
): Promise<void> {
  for (const rule of applied) {
    if (rule.state === 'removed') {
      await db
        .delete(generatedRules)
        .where(
          and(
            eq(generatedRules.repoId, repoId),
            eq(generatedRules.decisionId, rule.decisionId),
            eq(generatedRules.path, rule.path),
          ),
        )
      continue
    }

    await db
      .insert(generatedRules)
      .values({
        id: `${repoId}:${rule.decisionId}:${rule.path}`,
        repoId,
        componentId: rule.componentId,
        decisionId: rule.decisionId,
        path: rule.path,
        pathGlobs: rule.globs,
        contentHash: rule.contentHash,
        state: rule.state,
      })
      .onConflictDoUpdate({
        target: [generatedRules.repoId, generatedRules.path, generatedRules.decisionId],
        set: { contentHash: rule.contentHash, state: rule.state, generatedAt: new Date() },
      })
  }
}
